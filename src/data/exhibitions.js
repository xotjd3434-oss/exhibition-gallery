export function getStatus(item, today = new Date()) {
  const date = new Intl.DateTimeFormat("sv-SE", { timeZone: "Asia/Seoul" }).format(today);
  return date < item.start ? "예정" : date > item.end ? "종료" : "진행중";
}

export function dateRange(item) {
  return `${item.start.replaceAll("-", ".")} — ${item.end.replaceAll("-", ".")}`;
}

export function priceLabel(price) {
  return price === 0 ? "무료" : `${price.toLocaleString("ko-KR")}원`;
}

